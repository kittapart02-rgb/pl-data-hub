"""Download official club crests and player photos and embed them for an offline HTML file.

Run on your own machine (needs internet access to resources.premierleague.com):
    pip install pillow            # optional: shrinks photos ~10x; without it images are embedded as downloaded
    python3 etl/embed_images.py                  # players from the newest season + all clubs
    python3 etl/embed_images.py --seasons all    # every player in the dataset (bigger file)
    python3 build.py --images embedded           # -> dist/index-images.html

Crests and photos are copyrighted / trademarked. Use the result for personal viewing; do not publish it.
"""
import argparse, base64, io, json, sys, urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).parent.parent
DATA = ROOT / 'src' / 'data' / 'real-data.js'
OUT = ROOT / 'src' / 'data' / 'images.js'
PLAYER_URLS = ['https://resources.premierleague.com/premierleague25/photos/players/110x140/{code}.png',
               'https://resources.premierleague.com/premierleague/photos/players/110x140/p{code}.png']
TEAM_URLS = ['https://resources.premierleague.com/premierleague/badges/70/t{code}.png',
             'https://resources.premierleague.com/premierleague25/badges/{code}.png']

ap = argparse.ArgumentParser()
ap.add_argument('--seasons', default='latest', help="'latest', 'all', or comma-separated ids like 2026-27,2025-26")
ap.add_argument('--player-url', action='append', help='override player URL template(s); {code} is replaced')
ap.add_argument('--team-url', action='append', help='override crest URL template(s); {code} is replaced')
ap.add_argument('--size', type=int, default=96, help='photo height in pixels after resizing')
ap.add_argument('--workers', type=int, default=12)
args = ap.parse_args()

try:
    from PIL import Image
except ImportError:
    Image = None
    print('Pillow not installed: embedding images at original size (pip install pillow to shrink them).')

src = DATA.read_text(encoding='utf-8')
data = json.loads(src[src.index('{'):src.rstrip().rindex(';')])
seasons = data['seasons']
if args.seasons == 'latest':
    seasons = seasons[:1]
elif args.seasons != 'all':
    wanted = set(args.seasons.split(','))
    seasons = [s for s in seasons if s['id'] in wanted]
players = {}
for s in seasons:
    for row in s['players']:
        players.setdefault(row[0], row[4])
teams = sorted({t for s in seasons for t in s['teams']})
player_urls = args.player_url or PLAYER_URLS
team_urls = args.team_url or TEAM_URLS


def fetch(templates, code):
    for t in templates:
        url = t.format(code=code)
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (PL Data Hub personal use)'})
            with urllib.request.urlopen(req, timeout=20) as r:
                if r.status == 200:
                    return r.read(), r.headers.get('Content-Type', 'image/png').split(';')[0]
        except Exception:
            continue
    return None, None


def to_data_uri(raw, ctype, height):
    if Image is not None and ctype != 'image/svg+xml':
        img = Image.open(io.BytesIO(raw)).convert('RGBA')
        w = round(img.width * height / img.height)
        img = img.resize((w, height), Image.LANCZOS)
        buf = io.BytesIO(); img.save(buf, 'WEBP', quality=80); raw, ctype = buf.getvalue(), 'image/webp'
    return f'data:{ctype};base64,' + base64.b64encode(raw).decode()


def job(kind, key, code):
    raw, ctype = fetch(team_urls if kind == 'team' else player_urls, code)
    if raw is None:
        return kind, key, None
    return kind, key, to_data_uri(raw, ctype, 80 if kind == 'team' else args.size)


tasks = [('team', t, data['teamCodes'][t]) for t in teams] + [('player', pid, code) for pid, code in players.items()]
result = {'teams': {}, 'players': {}}
missing = {'team': 0, 'player': 0}
with ThreadPoolExecutor(args.workers) as ex:
    for i, (kind, key, uri) in enumerate(ex.map(lambda t: job(*t), tasks), 1):
        if uri:
            result['teams' if kind == 'team' else 'players'][key] = uri
        else:
            missing[kind] += 1
        if i % 100 == 0 or i == len(tasks):
            print(f'  {i}/{len(tasks)}', end='\r')
print()
OUT.write_text('/* Generated by etl/embed_images.py. Copyrighted images for personal use only. */\nconst IMAGE_DATA = '
               + json.dumps(result, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f"crests {len(result['teams'])}/{len(teams)}, photos {len(result['players'])}/{len(players)} "
      f"(missing: {missing['team']} crests, {missing['player']} photos -> generated fallback is used)")
print('written', OUT, OUT.stat().st_size // 1024, 'KB')
if len(result['teams']) + len(result['players']) == 0:
    sys.exit('Nothing downloaded: check your internet connection or the URL templates.')
